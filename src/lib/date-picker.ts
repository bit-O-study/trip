import type { MouseEvent } from "react";

/**
 * 날짜·시각 입력의 아무 곳이나 눌러도 달력이 열리게 한다.
 *
 * `type="date"` / `type="datetime-local"` 는 브라우저 기본 달력을 이미 갖고
 * 있지만, 크롬은 **오른쪽 끝의 작은 아이콘을 정확히 눌러야만** 열어 준다.
 * 모바일에서 그 아이콘은 손끝보다 작아서, 대부분의 사용자는 달력이 있는 줄도
 * 모르고 숫자를 직접 타이핑하게 된다.
 *
 * 직접 만든 달력 컴포넌트를 쓰지 않는 이유: 브라우저 기본 입력은 시각장애인용
 * 스크린리더, 모바일 네이티브 피커, 로캘별 날짜 표기를 이미 전부 지원한다.
 * 직접 만들면 그 셋을 전부 다시 구현해야 하고 대개 더 나빠진다.
 *
 * click 에만 건다. focus 에 걸면 키보드로 Tab 하며 지나갈 때마다 달력이 열려
 * 오히려 방해가 된다. 타이핑·화살표 입력 같은 기본 동작은 그대로 남는다.
 */
export function openDatePicker(event: MouseEvent<HTMLInputElement>) {
  const input = event.currentTarget;
  try {
    // 지원하지 않는 브라우저에서는 없는 메서드다. 그 경우 기존 동작 그대로.
    input.showPicker?.();
  } catch {
    // 사용자 제스처로 인정받지 못했거나 브라우저가 거부한 경우.
    // 달력이 안 열릴 뿐 입력 자체는 그대로 되므로 조용히 넘어간다.
  }
}
